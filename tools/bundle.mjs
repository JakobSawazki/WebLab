// Deliberately limited to WebLab's named imports and declaration exports.
// Fail closed when a module requires syntax this small bundler cannot handle.
export function bundleModules(sources, entry = "app.js") {
  const factories = Object.entries(sources).map(([id, source]) => {
    const names = [];
    source = source.replace(
      /^import\s*\{([\s\S]*?)\}\s*from\s*["']\.\/([a-z-]+\.js)["'];\s*/gm,
      (_, bindings, dependency) => {
        if (!(dependency in sources))
          throw new Error(`Missing module: ${dependency}`);
        if (!/^\s*\w+(?:\s*,\s*\w+)*\s*,?\s*$/.test(bindings))
          throw new Error(`Unsupported imports in ${id}`);
        return `const {${bindings}} = require(${JSON.stringify(dependency)});\n`;
      },
    );
    source = source.replace(
      /^export\s+((?:async\s+)?function|const)\s+(\w+)/gm,
      (_, declaration, name) => {
        names.push(name);
        return `${declaration} ${name}`;
      },
    );
    if (/^\s*(?:import|export)\b/m.test(source) || /\bimport\s*\(/.test(source))
      throw new Error(`Unsupported module syntax in ${id}`);
    return `${JSON.stringify(id)}: function(require) {\n${source}\nreturn {${names.join(",")}};\n}`;
  });
  if (!(entry in sources)) throw new Error(`Missing entry: ${entry}`);
  return `// Generated by tools/build-site.mjs. Edit the source modules instead.\n(function() {\n"use strict";\nconst modules = {\n${factories.join(",\n")}\n};\nconst cache = Object.create(null);\nfunction require(id) {\n  if (!(id in cache)) cache[id] = modules[id](require);\n  return cache[id];\n}\nrequire(${JSON.stringify(entry)});\n})();\n`;
}
